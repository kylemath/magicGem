"""
congruent_facets.py -- congruent facets of the 880 order-four gems (Remark rem:congruent-facets).
Two facets are congruent if some cyclic relabelling (rotation or reversal) of their vertex polygons preserves all
pairwise squared distances (a planar polygon is determined up to isometry by them). Facet orbits are taken under the
isometry group of the gem, which by Prop. prop:iso4 is generated by -id (associative squares), a half-turn about a
horizontal axis (the other self-complementary squares), or is trivial. A class of congruent facets is "accidental"
if it meets more than one orbit. Counted at the paper's scale (one unit per entry) and with the heights scaled by 1/5
(printed models and the paper nets of the web page); the face lattice is the same at both scales.
Exact integer arithmetic throughout. Usage: python3 congruent_facets.py  (about 1 min) -> congruent_facets.log
"""
import sys, os
import numpy as np
from collections import Counter, defaultdict
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from gem_geometry import exact_hull

squares = [np.array(list(map(int, l.split()))).reshape(4, 4) for l in open(os.path.join(HERE, 'squares880.txt')) if l.strip()]
assert len(squares) == 880
CANDIDATES = [np.diag([-1, -1, -1]), np.diag([1, -1, -1]), np.diag([-1, 1, -1])]

def cyclic(P, idx, normal):
    drop = int(np.abs(np.array(normal[:3], dtype=float)).argmax()); keep = [k for k in range(3) if k != drop]
    pts = np.array([P[i][keep] for i in idx], dtype=float); c = pts.mean(0)
    return [idx[k] for k in np.argsort(np.arctan2(pts[:, 1] - c[1], pts[:, 0] - c[0]))]

def shape(Q, cyc):
    k = len(cyc); best = None
    for r in range(k):
        for sgn in (1, -1):
            seq = [cyc[(r + sgn * t) % k] for t in range(k)]
            d = tuple(int(((Q[seq[i]] - Q[seq[j]]) ** 2).sum()) for i in range(k) for j in range(i + 1, k))
            best = d if best is None or d < best else best
    return (k, best)

log = []
for name, scale in (('paper scale', (5, 5, 5)), ('heights scaled by 1/5', (5, 5, 1))):
    tot = Counter()
    for S in squares:
        h = exact_hull(S); P = h['P']; Q = P * np.array(scale)
        facets = [cyclic(P, sorted(vs), key) for key, vs in h['faces'].items()]
        vset = {tuple(P[v]) for v in h['vertices']}
        G = [M for M in CANDIDATES if {tuple(M @ P[v]) for v in h['vertices']} == vset]
        assert len(G) <= 1
        index = {frozenset(tuple(P[v]) for v in cyc): i for i, cyc in enumerate(facets)}
        orbit = list(range(len(facets)))
        for i, cyc in enumerate(facets):
            for M in G:
                j = index[frozenset(tuple(M @ P[v]) for v in cyc)]
                orbit[i] = orbit[j] = min(orbit[i], orbit[j])
        classes = defaultdict(list)
        for i, cyc in enumerate(facets):
            classes[shape(Q, cyc)].append(i)
        kind = 'symmetric' if G else 'asymmetric'
        acc = [m for m in classes.values() if len({orbit[i] for i in m}) > 1]
        tot[kind, 'gems'] += 1
        tot[kind, 'facets'] += len(facets)
        tot[kind, 'facets with a congruent facet'] += sum(len(m) for m in classes.values() if len(m) > 1)
        tot[kind, 'facets in accidental classes'] += sum(len(m) for m in acc)
        tot[kind, 'gems with an accidental class'] += bool(acc)
        for m in acc:
            tot[kind, f'accidental classes of {len(facets[m[0]])}-gons'] += 1
    assert tot['symmetric', 'gems'] == 352
    for k in sorted(tot):
        log.append(f'{name}: {k[0]} gems: {k[1]}: {tot[k]}')
print('\n'.join(log))
open(os.path.join(HERE, 'congruent_facets.log'), 'w').write('\n'.join(log) + '\n')
