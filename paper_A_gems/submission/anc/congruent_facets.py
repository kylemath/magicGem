"""
congruent_facets.py -- congruent facets of the 880 order-four gems (Remark rem:congruent-facets) and the repeating
chains of facets of the symmetric gems (Remark rem:belts).
Two facets are congruent if some cyclic relabelling (rotation or reversal) of their vertex polygons preserves all
pairwise squared distances (a planar polygon is determined up to isometry by them). Facet orbits are taken under the
isometry group of the gem, which by Prop. prop:iso4 is generated by -id (associative squares), a half-turn about a
horizontal axis (the other self-complementary squares), or is trivial. A class of congruent facets is "accidental"
if it meets more than one orbit. Counted at the paper's scale (one unit per entry) and with the heights scaled by 1/5
(printed models and the paper nets of the web page); the face lattice is the same at both scales.
Belts: the facets crossed by a plane through 0 that contains no point form a closed chain, consecutive facets sharing an
edge that crosses the plane. For the associative gems (-id) the chain along z = 0 is checked to be mapped to itself
shifted half way round; for the half-turn gems the same is checked for the plane through 0 perpendicular to the axis,
and the chain along z = 0 is checked to be mapped to itself reversed.
Exact integer arithmetic throughout. Usage: python3 congruent_facets.py  (about 10 s) -> congruent_facets.log
"""
import sys, os
import numpy as np
from collections import Counter, defaultdict
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from gem_geometry import exact_hull

squares = [np.array(list(map(int, l.split()))).reshape(4, 4) for l in open(os.path.join(HERE, 'squares880.txt')) if l.strip()]
assert len(squares) == 880
CANDIDATES = [np.diag([-1, -1, -1]), np.diag([1, -1, -1]), np.diag([-1, 1, -1])]


def belt(P, faces, coord):
    """facets crossed by the plane {p[coord] = 0}, in cyclic order"""
    F = [f for f in faces if min(P[v][coord] for v in f) < 0 < max(P[v][coord] for v in f)]
    adj = defaultdict(list)
    for a in range(len(F)):
        for b in range(a + 1, len(F)):
            common = F[a] & F[b]
            if len(common) == 2 and np.prod([P[v][coord] for v in common]) < 0:
                adj[a].append(b); adj[b].append(a)
    assert all(len(adj[a]) == 2 for a in range(len(F)))
    cyc = [0, adj[0][0]]
    while len(cyc) < len(F):
        cyc.append([x for x in adj[cyc[-1]] if x != cyc[-2]][0])
    assert cyc[0] in adj[cyc[-1]]
    return [F[i] for i in cyc]


def belt_action(P, faces, coord, M):
    """'shift' if M maps the belt to itself shifted half way round, 'reversal' if it reverses it"""
    B = belt(P, faces, coord); m = len(B); pos = {f: i for i, f in enumerate(B)}
    index = {frozenset(tuple(P[v]) for v in f): f for f in faces}
    img = [pos[index[frozenset(tuple(M @ P[v]) for v in f)]] for f in B]
    if m % 2 == 0 and all(img[i] == (i + m // 2) % m for i in range(m)):
        return 'shift', m
    if any(all(img[i] == (c - i) % m for i in range(m)) for c in range(m)):
        return 'reversal', m
    return 'other', m

def cyclic(P, idx, normal):
    drop = int(np.abs(np.array(normal[:3], dtype=float)).argmax()); keep = [k for k in range(3) if k != drop]
    pts = np.array([P[i][keep] for i in idx], dtype=float); c = pts.mean(0)
    return [idx[k] for k in np.argsort(np.arctan2(pts[:, 1] - c[1], pts[:, 0] - c[0]))]

def shape(Q, cyc):
    k = len(cyc); best = None
    for r in range(k):
        for sgn in (1, -1):
            seq = [cyc[(r + sgn * t) % k] for t in range(k)]
            d = tuple(int(((Q[seq[i]] - Q[seq[j]]) ** 2).sum()) for i in range(k) for j in range(i + 1, k))
            best = d if best is None or d < best else best
    return (k, best)

log = []
belts = Counter()
for S in squares:
    h = exact_hull(S); P = h['P']; faces = list(h['faces'].values())
    vset = {tuple(P[v]) for v in h['vertices']}
    G = [M for M in CANDIDATES if {tuple(M @ P[v]) for v in h['vertices']} == vset]
    if not G:
        continue
    M = G[0]
    if (M == CANDIDATES[0]).all():
        act, m = belt_action(P, faces, 2, M); belts['associative, plane z=0', act, m] += 1
    else:
        axis = 0 if M[0, 0] == 1 else 1
        act, m = belt_action(P, faces, axis, M); belts['half-turn, plane perpendicular to the axis', act, m] += 1
        act, m = belt_action(P, faces, 2, M); belts['half-turn, plane z=0', act, m] += 1
for (plane, act) in sorted({(k[0], k[1]) for k in belts}):
    ms = {k[2]: v for k, v in belts.items() if k[0] == plane and k[1] == act}
    log.append(f'belts, {plane}: {act} for {sum(ms.values())} gems; chain lengths {dict(sorted(ms.items()))}')
assert {(k[0], k[1]) for k in belts} == {('associative, plane z=0', 'shift'), ('half-turn, plane perpendicular to the axis', 'shift'), ('half-turn, plane z=0', 'reversal')}
for name, scale in (('paper scale', (5, 5, 5)), ('heights scaled by 1/5', (5, 5, 1))):
    tot = Counter()
    for S in squares:
        h = exact_hull(S); P = h['P']; Q = P * np.array(scale)
        facets = [cyclic(P, sorted(vs), key) for key, vs in h['faces'].items()]
        vset = {tuple(P[v]) for v in h['vertices']}
        G = [M for M in CANDIDATES if {tuple(M @ P[v]) for v in h['vertices']} == vset]
        assert len(G) <= 1
        index = {frozenset(tuple(P[v]) for v in cyc): i for i, cyc in enumerate(facets)}
        orbit = list(range(len(facets)))
        for i, cyc in enumerate(facets):
            for M in G:
                j = index[frozenset(tuple(M @ P[v]) for v in cyc)]
                orbit[i] = orbit[j] = min(orbit[i], orbit[j])
        classes = defaultdict(list)
        for i, cyc in enumerate(facets):
            classes[shape(Q, cyc)].append(i)
        kind = 'symmetric' if G else 'asymmetric'
        acc = [m for m in classes.values() if len({orbit[i] for i in m}) > 1]
        tot[kind, 'gems'] += 1
        tot[kind, 'facets'] += len(facets)
        tot[kind, 'facets with a congruent facet'] += sum(len(m) for m in classes.values() if len(m) > 1)
        tot[kind, 'facets in accidental classes'] += sum(len(m) for m in acc)
        tot[kind, 'gems with an accidental class'] += bool(acc)
        for m in acc:
            tot[kind, f'accidental classes of {len(facets[m[0]])}-gons'] += 1
    assert tot['symmetric', 'gems'] == 352
    for k in sorted(tot):
        log.append(f'{name}: {k[0]} gems: {k[1]}: {tot[k]}')
print('\n'.join(log))
open(os.path.join(HERE, 'congruent_facets.log'), 'w').write('\n'.join(log) + '\n')
