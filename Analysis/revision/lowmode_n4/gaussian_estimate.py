#!/usr/bin/env python3
"""
Gaussian local-limit estimate of |L_n| (low-mode balanced class) and of the
two-condition classes XY = {Cov(X,Z)=Cov(Y,Z)=0} and DIAG = {both diagonals = M}.

Statistics (all linear in the arrangement s, uniform random permutation of 1..N):
    T1 = sum_{ij} j s_ij,  T2 = sum_{ij} i s_ij,  T3 = main diagonal sum,  T4 = anti diagonal sum.
For T = sum_c a_c s_{pi(c)} with pi uniform, exact permutation moments are
    E[T] = sum_c a_c * mean(b),
    Cov(T, T') = (1/(N-1)) * sum_c (a_c - abar)(a'_c - abar') * sum_v (v - vbar)^2 .
The targets equal the exact means, so the local-limit estimate is
    count_est = N! * phi_Sigma(0) * vol(lattice cell),
with phi_Sigma the centred d-variate Gaussian density and the lattice the integer
lattice generated by single-transposition steps (its index in Z^d is computed below
by a Smith normal form; it is 1 for every n considered, so vol = 1).

Writes gaussian_estimates.json.  No heavy computation.
"""
import json, math, itertools, sys, os
import numpy as np
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import smith_normal_form

HERE = os.path.dirname(os.path.abspath(__file__))

def weights(n):
    N = n * n
    cells = [(c // n, c % n) for c in range(N)]
    A = np.array([[j for (i, j) in cells],
                  [i for (i, j) in cells],
                  [1 if i == j else 0 for (i, j) in cells],
                  [1 if i + j == n - 1 else 0 for (i, j) in cells]], dtype=float)
    return A

def perm_cov(A, N):
    b = np.arange(1, N + 1, dtype=float)
    Sb = ((b - b.mean()) ** 2).sum()
    Ac = A - A.mean(axis=1, keepdims=True)
    return (Ac @ Ac.T) * Sb / (N - 1)

def lattice_index(A):
    """Index in Z^d of the lattice generated by w_c - w_c' over all cell pairs (value difference 1)."""
    d, N = A.shape
    rows = []
    for c in range(N):
        for c2 in range(c + 1, N):
            v = (A[:, c] - A[:, c2]).astype(int)
            if np.any(v):
                rows.append(list(v))
    M = Matrix(rows)
    S = smith_normal_form(M, domain=ZZ)
    diag = [abs(int(S[i, i])) for i in range(min(S.shape))]
    nz = [x for x in diag if x != 0]
    return int(np.prod(nz)) if len(nz) == d else None  # None = not full rank

def gauss_count(n, idx):
    N = n * n
    A = weights(n)
    S = perm_cov(A, N)[np.ix_(idx, idx)]
    d = len(idx)
    dens = (2 * math.pi) ** (-d / 2) / math.sqrt(np.linalg.det(S))
    return math.factorial(N) * dens, dens, S

def main():
    exact = {  # from lowmode_enum (n=3 exhaustive-equivalent, n=4 meet in the middle)
        3: {"L": 8, "XY": 760, "DIAG": 4224},
        4: {"L": 14639440, "XY": 6697177424, "DIAG": 49932288000},
    }
    out = {"description": __doc__.strip(), "per_n": {}}
    for n in range(3, 9):
        N = n * n
        A = weights(n)
        S = perm_cov(A, N)
        rec = {"N_factorial": str(math.factorial(N)), "cov_T1T2T3T4": S.tolist(),
               "sd": np.sqrt(np.diag(S)).tolist(),
               "corr_T3T4": float(S[2, 3] / math.sqrt(S[2, 2] * S[3, 3]))}
        rec["lattice_index_L"] = lattice_index(A)
        rec["lattice_index_XY"] = lattice_index(A[:2])
        rec["lattice_index_DIAG"] = lattice_index(A[2:])
        for name, idx in (("L", [0, 1, 2, 3]), ("XY", [0, 1]), ("DIAG", [2, 3])):
            est, dens, _ = gauss_count(n, idx)
            rec[f"gauss_prob_{name}"] = dens
            rec[f"gauss_count_{name}"] = est
            if n in exact:
                rec[f"exact_{name}"] = exact[n][name]
                rec[f"ratio_exact_over_gauss_{name}"] = exact[n][name] / est
        out["per_n"][str(n)] = rec
    with open(os.path.join(HERE, "gaussian_estimates.json"), "w") as f:
        json.dump(out, f, indent=1)
    for n, rec in out["per_n"].items():
        print(f"n={n}: sd={['%.2f' % x for x in rec['sd']]} corr34={rec['corr_T3T4']:.3f} "
              f"lattice idx L/XY/DIAG={rec['lattice_index_L']}/{rec['lattice_index_XY']}/{rec['lattice_index_DIAG']}")
        for name in ("L", "XY", "DIAG"):
            s = f"   {name:5s} gauss={rec['gauss_count_'+name]:.4e} prob={rec['gauss_prob_'+name]:.3e}"
            if f"exact_{name}" in rec:
                s += f"  exact={rec['exact_'+name]}  ratio={rec['ratio_exact_over_gauss_'+name]:.4f}"
            print(s)

if __name__ == "__main__":
    main()
