"""Write arxiv_submission/sections/witnesses.tex: the witness arrangements for k*(n)=n-1, 5<=n<=13,
taken verbatim from Analysis/revision/theory/results.json (permutation_threshold_search) and re-verified
by check_round1.py.  Compact listing: rows separated by slashes, small typewriter font."""
import json, os
from math import comb
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
R = json.load(open(f'{ROOT}/Analysis/revision/theory/results.json'))
key = [k for k in R if k.startswith('permutation_threshold_search')][0]
lines = ['% generated by Analysis/revision_round1/make_witness_table.py -- do not edit by hand',
         '{\\scriptsize\\ttfamily\\setlength{\\parindent}{0pt}\\setlength{\\parskip}{2pt}']
for n in range(5, 14):
    S = np.array(R[key][str(n)]['square'])
    N = n * n; M = n * (N + 1) // 2
    assert sorted(S.ravel().tolist()) == list(range(1, N + 1))
    assert (S.sum(1) == M).all()
    assert (S.sum(0) - M == np.array([(-1) ** j * comb(n - 1, j) for j in range(n)])).all()
    body = ' / '.join(' '.join(str(v) for v in row) for row in S)
    lines.append(f'\\textrm{{$n={n}$, $M(n)={M}$:}} {body}\\par')
lines.append('}')
open(f'{ROOT}/arxiv_submission/sections/witnesses.tex', 'w').write('\n'.join(lines) + '\n')
print('wrote sections/witnesses.tex')
